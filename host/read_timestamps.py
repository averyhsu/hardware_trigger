#!/usr/bin/env python3
"""
Read Alvium frame timestamps under external trigger and report the measured
inter-frame interval + frame rate. Use this to verify the Teensy trigger fps.

The timestamp is generated by the CAMERA's own clock when it acquires each
frame (it is embedded in the frame, NOT the host USB-receive time), so the
interval between consecutive frames is an independent cross-check of the
Teensy's commanded fps — two different oscillators being compared, immune to
USB transfer latency and host scheduling jitter.

Every run writes a per-frame CSV (see OUTPUT_CSV below): frame_id, the camera
timestamp, the interval to the previous frame, and the frame status.

Requires: the Vimba X SDK/runtime installed system-wide, plus the matching
          `vmbpy` wheel (ships inside the SDK — it is NOT on PyPI). See
          host/SETUP.md for the full Linux setup.

Examples:
    python3 read_timestamps.py                 # capture DEFAULT_FRAMES frames
    python3 read_timestamps.py 200             # capture 200 frames
    python3 read_timestamps.py --list-cameras  # list detected cameras and exit
    python3 read_timestamps.py --list-lines    # show selectable trigger inputs
"""

import argparse
import sys
import time

# ============================================================================
#  RIG CONFIGURATION — edit these to match your setup
# ============================================================================
TRIGGER_SOURCE   = 'Line0'   # camera input line wired to the Teensy TRIG_PIN
EXPOSURE_US      = 200       # camera ExposureTime in microseconds (Timed mode)
PIXEL_FORMAT     = 'BayerRG8'  # 1 B/px (1/3 of RGB8) -> 3x the frame rate for a
                             #   given bandwidth. 'Mono8' for grayscale; 'RGB8'
                             #   for on-camera color (heavy). BayerRG8 keeps
                             #   color at 1 B/px — debayer on the host.
THROUGHPUT_LIMIT_BPS = 450_000_000  # camera DeviceLinkThroughputLimit (range
                             #   18e6..450e6 on this model). Raise toward 450e6
                             #   ONLY after raising host usbfs_memory_mb (16->1000),
                             #   or the host starves and frames come back INCOMPLETE.
OUTPUT_CSV       = 'timestamps.csv'  # per-frame log; written every run (cwd-relative)
BUFFER_COUNT     = 30        # async stream buffers; keep high so the host never
                             #   back-pressures the camera (a per-frame print/CSV
                             #   loop DOES, and silently caps the measured rate)
DEFAULT_FRAMES   = 100       # frames to capture when none given on the command line
FRAME_TIMEOUT_MS = 2000      # per-frame wait; must exceed one trigger period
                             #   (>91 ms @ 11 fps). Raise for slower trigger rates.
# ============================================================================


def load_vmbpy():
    """Import vmbpy into module globals, or exit with a helpful message.

    vmbpy loads the native VmbC library at import time; if the Vimba X runtime
    is not installed system-wide, this import fails. Deferred until after arg
    parsing so `--help` works without the SDK present.
    """
    try:
        from vmbpy import (VmbSystem, VmbFeatureError, VmbTimeout,
                           FrameStatus)
    except (ImportError, OSError) as exc:
        sys.exit(
            f"Could not load vmbpy ({exc}).\n"
            "  - Is the Vimba X SDK/runtime installed system-wide?\n"
            "  - Is the matching vmbpy wheel installed in this environment?\n"
            "See host/SETUP.md for the Linux install steps."
        )
    globals().update(VmbSystem=VmbSystem, VmbFeatureError=VmbFeatureError,
                     VmbTimeout=VmbTimeout, FrameStatus=FrameStatus)


def parse_args():
    p = argparse.ArgumentParser(
        description="Measure Alvium inter-frame timing under external trigger. "
                    "Rig settings (trigger line, exposure, CSV path) live as "
                    "constants at the top of this file.")
    p.add_argument('num_frames', nargs='?', type=int, default=DEFAULT_FRAMES,
                   help=f"frames to capture (default {DEFAULT_FRAMES})")
    p.add_argument('--camera-id',
                   help="open this camera id/serial instead of auto-selecting "
                        "(needed if more than one real camera is present)")
    p.add_argument('--list-cameras', action='store_true',
                   help="list all detected cameras and exit")
    p.add_argument('--list-lines', action='store_true',
                   help="print the camera's selectable TriggerSource lines and exit")
    return p.parse_args()


def try_set(cam, name, value):
    """Set a feature if the model has it; otherwise skip quietly."""
    try:
        cam.get_feature_by_name(name).set(value)
        print(f"  {name} = {value}")
        return True
    except (VmbFeatureError, AttributeError):
        print(f"  {name}: not available (skipped)")
        return False


def try_get(cam, name):
    """Read a feature value, or None if the model doesn't expose it."""
    try:
        return cam.get_feature_by_name(name).get()
    except (VmbFeatureError, AttributeError):
        return None


def try_run(cam, *names):
    """Run the first command feature that exists (name varies by model/TL)."""
    for name in names:
        try:
            cam.get_feature_by_name(name).run()
            print(f"  ran {name}")
            return
        except (VmbFeatureError, AttributeError):
            continue
    print(f"  none of {names} available (timestamp not reset)")


def enum_entries(cam, name):
    """Available entries of an enum feature as plain strings ([] if absent)."""
    try:
        feat = cam.get_feature_by_name(name)
        return [str(e) for e in feat.get_available_entries()]
    except (VmbFeatureError, AttributeError):
        return []


def list_lines(cam):
    """Print the TriggerSource options so you can pick the wired input."""
    print(f"Camera: {cam.get_id()}")
    sources = enum_entries(cam, 'TriggerSource')
    if sources:
        print("Selectable TriggerSource values:")
        for s in sources:
            print(f"  {s}")
    else:
        print("TriggerSource enum not readable on this model.")
    lines = enum_entries(cam, 'LineSelector')
    if lines:
        print("Selectable LineSelector (physical I/O) values:")
        for ln in lines:
            print(f"  {ln}")


def is_simulator(cam):
    """True for the GenTL Camera Simulator transport-layer devices."""
    return 'Simulator' in (cam.get_model() or '')


def describe(cam):
    return f"{cam.get_id()}  {cam.get_model()}  (serial {cam.get_serial()})"


def select_camera(cams, camera_id):
    """Pick the camera to use: explicit id wins; else the sole real (non-sim) one."""
    if camera_id:
        for c in cams:
            if camera_id in (c.get_id(), c.get_serial()):
                return c
        sys.exit(f"Camera id/serial '{camera_id}' not found. "
                 f"Use --list-cameras to see options.")
    real = [c for c in cams if not is_simulator(c)]
    if len(real) == 1:
        return real[0]
    if not real:
        sys.exit("Only simulator cameras detected — no real Alvium found. "
                 "Check USB connection/power. Use --list-cameras to inspect.")
    ids = ', '.join(c.get_id() for c in real)
    sys.exit(f"Multiple real cameras detected ({ids}). "
             f"Pick one with --camera-id <id-or-serial>.")


def timestamp_hz(cam):
    """Ticks-per-second for the frame timestamp. USB3 Alvium reports ns (1 GHz)."""
    for name in ('DeviceTimestampFrequency', 'GevTimestampTickFrequency'):
        try:
            return float(cam.get_feature_by_name(name).get())
        except (VmbFeatureError, AttributeError):
            continue
    return 1e9  # U3V default: timestamp is already in nanoseconds


def configure_trigger(cam):
    print("Configuring external trigger (FrameStart / Timed):")
    # Payload/bandwidth settings first — must be set while not streaming.
    try_set(cam, 'PixelFormat',       PIXEL_FORMAT)
    try_set(cam, 'DeviceLinkThroughputLimitMode', 'On')
    try_set(cam, 'DeviceLinkThroughputLimit',     int(THROUGHPUT_LIMIT_BPS))
    try_set(cam, 'AcquisitionMode',   'Continuous')
    try_set(cam, 'TriggerSelector',   'FrameStart')
    if not try_set(cam, 'TriggerSource', TRIGGER_SOURCE):
        avail = enum_entries(cam, 'TriggerSource')
        if avail:
            print(f"  -> available sources: {', '.join(avail)}")
            print("     set TRIGGER_SOURCE at the top of this file to one of them")
    try_set(cam, 'TriggerActivation', 'RisingEdge')
    try_set(cam, 'ExposureMode',      'Timed')
    try_set(cam, 'ExposureTime',      float(EXPOSURE_US))
    # Disable the internal free-run rate generator so the EXTERNAL trigger drives
    # FrameStart. If left enabled the camera free-runs at AcquisitionFrameRate and
    # silently ignores the trigger (measured rate would match the internal rate,
    # not the Teensy).
    try_set(cam, 'AcquisitionFrameRateEnable', False)
    try_set(cam, 'TriggerMode',       'On')      # enable last


def report_limits(cam):
    """Print the features that cap the achievable frame rate (fps diagnostics).

    A frame-rate ceiling under external trigger usually comes from exposure +
    sensor readout, or a USB bandwidth throttle (DeviceLinkThroughputLimit) —
    NOT from the Vimba X viewer's live-display refresh, which is only a host
    estimate. These readbacks help tell those apart.
    """
    print("Camera limits (fps diagnostics):")
    exp = try_get(cam, 'ExposureTime')
    if exp is not None:
        print(f"  ExposureTime          = {exp:.1f} us "
              f"(exposure alone allows <= {1e6 / exp:.1f} fps)")
    readout = try_get(cam, 'SensorReadoutTime')
    if readout is not None:
        print(f"  SensorReadoutTime     = {readout:.1f} us")
    mode = try_get(cam, 'DeviceLinkThroughputLimitMode')
    limit = try_get(cam, 'DeviceLinkThroughputLimit')
    if mode is not None or limit is not None:
        print(f"  DeviceLinkThroughputLimitMode = {mode}")
        if limit is not None:
            print(f"  DeviceLinkThroughputLimit     = {limit} B/s")
    fr_en = try_get(cam, 'AcquisitionFrameRateEnable')
    fr = try_get(cam, 'AcquisitionFrameRate')
    if fr_en is not None or fr is not None:
        print(f"  AcquisitionFrameRateEnable    = {fr_en}  "
              f"AcquisitionFrameRate = {fr}")


def capture(cam, num_frames, csv_path):
    print("Resetting camera timestamp clock:")
    try_run(cam, 'TimestampReset', 'GevTimestampControlReset')

    hz = timestamp_hz(cam)
    print(f"Timestamp tick rate: {hz:.0f} Hz  ({1e9 / hz:.3f} ns/tick)")
    print(f"\nCapturing {num_frames} frames -> {csv_path} (async streaming, "
          f"{BUFFER_COUNT} buffers; Ctrl-C to stop early)...")

    # Minimal callback: copy out (id, timestamp, status) and immediately requeue
    # the buffer. Any real per-frame work here (print, CSV, decode) would stall
    # the pipeline and make the camera drop frames — do it after streaming stops.
    records = []
    def handler(c, stream, frame):
        records.append((frame.get_id(), frame.get_timestamp(),
                        frame.get_status() == FrameStatus.Complete))
        c.queue_frame(frame)

    cam.start_streaming(handler=handler, buffer_count=BUFFER_COUNT)
    try:
        last_n, last_progress = 0, time.monotonic()
        while len(records) < num_frames:
            time.sleep(0.02)
            n = len(records)
            if n > last_n:
                last_n, last_progress = n, time.monotonic()
            elif (time.monotonic() - last_progress) * 1000 > FRAME_TIMEOUT_MS:
                print(f"Timed out (>{FRAME_TIMEOUT_MS} ms with no new frame). "
                      "Are triggers arriving? Check wiring/ground and the Teensy.")
                break
    except KeyboardInterrupt:
        print("(stopped early)")
    finally:
        cam.stop_streaming()

    # Reduce + write CSV after streaming has stopped (I/O off the hot path).
    records = records[:num_frames]
    deltas, incomplete, prev = [], 0, None
    with open(csv_path, 'w') as f:
        f.write("frame_id,timestamp_ticks,dt_s,status\n")
        for fid, ts, ok in records:
            if not ok:
                incomplete += 1
            dt_s = (ts - prev) / hz if prev is not None else None
            if dt_s is not None:
                deltas.append(dt_s)
            f.write(f"{fid},{ts},{'' if dt_s is None else dt_s},"
                    f"{'Complete' if ok else 'Incomplete'}\n")
            prev = ts
    print(f"wrote {csv_path}  ({len(records)} frames)")
    summarize(deltas, incomplete)


def summarize(deltas, incomplete):
    if not deltas:
        print("\nNo intervals measured — did any triggers arrive? "
              "Check wiring, shared ground, and that the Teensy is running.")
        return
    n = len(deltas)
    mean = sum(deltas) / n
    std = (sum((d - mean) ** 2 for d in deltas) / n) ** 0.5
    p2p = max(deltas) - min(deltas)
    print("\n---- summary ----")
    print(f"frames measured : {n + 1}")
    print(f"mean interval   : {mean * 1e3:.5f} ms")
    print(f"measured fps    : {1.0 / mean:.5f} Hz")
    print(f"interval std dev: {std * 1e6:.2f} us   (trigger jitter)")
    print(f"peak-to-peak    : {p2p * 1e6:.2f} us")
    if incomplete:
        print(f"incomplete frames: {incomplete}   (dropped/partial transfers)")


def main():
    args = parse_args()
    load_vmbpy()
    with VmbSystem.get_instance() as vmb:
        cams = vmb.get_all_cameras()
        if not cams:
            sys.exit("No camera found. Is the Alvium connected and powered, "
                     "and are USB permissions set up? See host/SETUP.md.")
        if args.list_cameras:
            print(f"{len(cams)} camera(s) detected:")
            for c in cams:
                tag = ' [simulator]' if is_simulator(c) else ''
                print(f"  {describe(c)}{tag}")
            return
        cam = select_camera(cams, args.camera_id)
        with cam:
            if args.list_lines:
                list_lines(cam)
                return
            print(f"Camera: {describe(cam)}")
            configure_trigger(cam)
            report_limits(cam)
            capture(cam, args.num_frames, OUTPUT_CSV)


if __name__ == '__main__':
    main()
